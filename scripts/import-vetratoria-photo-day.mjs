import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = "/assets/img/media/dahab/photo-day";
const outputRoot = path.join(root, "assets", "img", "media", "dahab", "photo-day");
const dataFile = path.join(root, "src", "media-photo-day.mjs");

const albums = [
  {
    slug: "2026-06-07-photo-day",
    title: "Фото дня 06–07 июня",
    date: "2026-06-07",
    source: "https://vetratoria.ru/gallery/foto-dnya-06-07-iyunya.php"
  },
  {
    slug: "2026-06-03-photo-day",
    title: "Фото дня 02–03 июня",
    date: "2026-06-03",
    source: "https://vetratoria.ru/gallery/foto-dnya-02-03-iyunya.php"
  },
  {
    slug: "2026-05-31-photo-day",
    title: "Фото дня 30–31 мая",
    date: "2026-05-31",
    source: "https://vetratoria.ru/gallery/foto-dnya-30-31-maya.php"
  },
  {
    slug: "2026-05-26-photo-day",
    title: "Фото дня 26 мая",
    date: "2026-05-26",
    source: "https://vetratoria.ru/gallery/foto-dnya-26-maya.php"
  },
  {
    slug: "2026-05-24-photo-day",
    title: "Фото дня 24 мая",
    date: "2026-05-24",
    source: "https://vetratoria.ru/gallery/foto-dnya-24-maya.php"
  }
];

const fetchOk = async (url) => {
  const response = await fetch(url, {
    headers: {
      "user-agent": "Vetratoria media importer"
    }
  });

  if (!response.ok) {
    throw new Error(`Не удалось загрузить ${url}: ${response.status} ${response.statusText}`);
  }

  return response;
};

const originalPhotoUrls = (html) => [
  ...new Set(
    [...html.matchAll(/href="(https:\/\/vetratoria\.ru\/sites\/default\/files\/portfolio\/[^"]+\.(?:jpe?g|png|webp))"/gi)]
      .map((match) => match[1].replaceAll("&amp;", "&"))
  )
];

const importedAlbums = [];

for (const album of albums) {
  const html = await (await fetchOk(album.source)).text();
  const photoUrls = originalPhotoUrls(html);

  if (!photoUrls.length) {
    throw new Error(`В альбоме «${album.title}» не найдены оригиналы фотографий.`);
  }

  const albumDirectory = path.join(outputRoot, album.slug);
  await mkdir(albumDirectory, { recursive: true });

  const photos = [];
  for (const [index, photoUrl] of photoUrls.entries()) {
    const extension = path.extname(new URL(photoUrl).pathname).toLowerCase() || ".jpg";
    const filename = `${String(index + 1).padStart(2, "0")}${extension}`;
    const outputFile = path.join(albumDirectory, filename);
    const bytes = Buffer.from(await (await fetchOk(photoUrl)).arrayBuffer());
    await writeFile(outputFile, bytes);
    photos.push(`${publicRoot}/${album.slug}/${filename}`);
  }

  importedAlbums.push({
    country: "dahab",
    slug: album.slug,
    title: album.title,
    date: album.date,
    sport: "windsurf",
    event: "photo-day",
    description: "Свежие кадры с воды: виндсерфинг, ученики и райдеры Vetratoria в лагуне Дахаба.",
    source: album.source,
    cover: photos[0],
    photos
  });

  console.log(`${album.title}: ${photos.length} фото`);
}

const output = `// Generated by scripts/import-vetratoria-photo-day.mjs\nexport const photoDayAlbums = ${JSON.stringify(importedAlbums, null, 2)};\n`;
await writeFile(dataFile, output, "utf8");
console.log(`Данные сохранены: ${path.relative(root, dataFile)}`);
